// Compile @capsule/core's manifest JSON Schema into a standalone validator
// module, so the browser enforces the exact same schema as the Node
// reference implementation without runtime code generation (`new Function`
// is forbidden by the viewer's Content-Security-Policy).
import { promises as fs } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";
import Ajv from "ajv";
import addFormats from "ajv-formats";
import standaloneCode from "ajv/dist/standalone/index.js";

const here = path.dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
const schemaPath = require.resolve("@capsule/core/manifest.schema.json");
const outDir = path.join(here, "..", "src", "generated");

const schema = JSON.parse(await fs.readFile(schemaPath, "utf8"));
const ajv = new Ajv({ allErrors: true, strict: false, code: { source: true, esm: true } });
addFormats(ajv);
const code = standaloneCode(ajv, ajv.compile(schema));

const header = `// GENERATED by scripts/gen-validator.mjs from @capsule/core/src/manifest.schema.json.\n// Do not edit. Regenerated on every build, test, and typecheck.\n`;
const dts = `${header}declare const validate: ((data: unknown) => boolean) & {\n  errors?: Array<{ instancePath?: string; message?: string }> | null;\n};\nexport default validate;\n`;

await fs.mkdir(outDir, { recursive: true });
await writeIfChanged(path.join(outDir, "manifest-validator.js"), header + code);
await writeIfChanged(path.join(outDir, "manifest-validator.d.ts"), dts);

async function writeIfChanged(file, content) {
  const existing = await fs.readFile(file, "utf8").catch(() => null);
  if (existing !== content) await fs.writeFile(file, content);
}
